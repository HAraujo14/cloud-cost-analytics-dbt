with aggregated as (
    select
        usage_date,
        billing_month,
        cloud_provider,
        account_id,
        service_name,
        usage_type,
        usage_unit,
        region,
        team,
        environment,
        cost_center,
        application,
        max(account_name) as account_name,
        max(service_code) as service_code,
        sum(usage_amount) as usage_amount,
        sum(gross_cost) as gross_cost,
        sum(credit_amount) as credit_amount,
        sum(gross_cost) - sum(credit_amount) as net_cost,
        count(*) as line_count,
        bool_and(is_synthetic) as is_synthetic,
        min(dataset_label) as dataset_label
    from {{ ref('int_cost_lines') }}
    group by
        usage_date,
        billing_month,
        cloud_provider,
        account_id,
        service_name,
        usage_type,
        usage_unit,
        region,
        team,
        environment,
        cost_center,
        application
)

select
    {{ surrogate_key([
        'usage_date',
        'cloud_provider',
        'account_id',
        'service_name',
        'usage_type',
        'usage_unit',
        'region',
        'team',
        'environment',
        'cost_center',
        'application'
    ]) }} as daily_cost_key,
    usage_date,
    billing_month,
    cloud_provider,
    account_id,
    account_name,
    service_name,
    service_code,
    usage_type,
    usage_unit,
    region,
    team,
    environment,
    cost_center,
    application,
    usage_amount,
    gross_cost,
    credit_amount,
    net_cost,
    line_count,
    is_synthetic,
    dataset_label
from aggregated
